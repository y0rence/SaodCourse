#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Приводит все README.md к строгому монохромному стилю проекта:
   - убирает цветные shields.io-бейджи;
   - убирает эмодзи из заголовков, списков и подзаголовков;
   - ✅/❌/⚠️ в таблицах заменяет на текст (да / нет / предупреждение);
   - не трогает типографские стрелки (← → ↔) в псевдокоде.
   Идемпотентен."""
import glob
import re

STRIP = ['🎯', '📚', '🗂', '🛠', '🧭', '📁', '📑', '⚡', '🧮', '🌿',
         '📘', '📝', '🖥', '🧩', '💼', '📖', '🧪', '📈', '🔹', '🔍',
         '💡', '🔁', '🎚', '🔧', '📌', '⭐', '📘']

# цветные маркеры статусов — только осмысленная замена
STATUS = [
    ('✅ сильно', 'да, сильно'),
    ('❌ нет', 'нет'),
    ('⚠️ только ', 'только '),
    ('⚠️ слабая:', 'слабая:'),
    ('⚠️ слабо', 'слабо'),
    ('⚠️ `M` нет, `C` слабо', '`M` нет, `C` слабо'),
    ('⚠️ При больших', 'При больших'),
    ('⚠️ Пирамида', 'Пирамида'),
    ('❌ неустойчивая', 'неустойчивая'),
    ('✅ устойчивая', 'устойчивая'),
    ('❌ |', 'нет |'),
    ('✅ |', 'да |'),
    ('⚠️ ', ''),
    ('✅', 'да'),
    ('❌', 'нет'),
]

BADGE = re.compile(r'^!\[[^\]]*\]\(https://img\.shields\.io/[^)]*\)\s*\n', re.M)

changed = []
for f in sorted(glob.glob('**/README*.md', recursive=True)):
    if '.git/' in f:
        continue
    s = orig = open(f, encoding='utf-8').read()
    s = BADGE.sub('', s)
    for a, b in STATUS:
        s = s.replace(a, b)
    for e in STRIP:
        s = s.replace(e + ' ', '')          # эмодзи + пробел в начале слова
        s = s.replace(e, '')                # одиночные
    # подчистка пустых строк подряд (максимум одна пустая)
    s = re.sub(r'\n{4,}', '\n\n\n', s)
    # строка-ссылка на интерактивную страницу без эмодзи
    s = s.replace('>  **Интерактивная', '> **Интерактивная')
    s = s.replace('> **Интерактивная страница:**', '> **Интерактивная страница:**')
    if s != orig:
        open(f, 'w', encoding='utf-8').write(s)
        changed.append(f)

print('Изменено файлов:', len(changed))
for c in changed:
    print(' -', c)
