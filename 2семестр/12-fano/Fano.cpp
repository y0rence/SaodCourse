// Побуквенный статический код Фано — задания 2, 3 и 4 (пособие СиАОД, п. 16.5).
//
// Обозначения, используемые в программе (по псевдокоду пособия):
//   n_i       — количество появлений конкретного символа в тексте;
//   N         — общее количество символов в файле;
//   P_i       = n_i / N — вероятность появления символа; массив P хранится
//               с индексами 1..n и упорядочен по убыванию;
//   C[i,k]    — k-й разряд кодового слова символа i (0 или 1);
//   Length[i] — длина кодового слова символа i;
//   L, R      — левая и правая границы обрабатываемой части массива P;
//   k         — длина уже построенной части элементарных кодов;
//   m         — индекс медианы (точка разбиения отрезка [L..R]);
//   SL, SR    — суммы вероятностей первой и второй частей отрезка (функция Med);
//   wes       — сумма весов (вероятностей) рабочей части массива (алгоритм А2);
//   summa     — накопленная сумма весов перед текущим элементом (алгоритм А2);
//   H         — энтропия исходного текста: H = -sum(P_i * log2 P_i);
//   Lcp       — средняя длина кодового слова: Lcp = sum(P_i * Length[i]);
//   r         — избыточность кода: r = Lcp - H (пособие, п. 16.3).
//
// Компиляция:  clang++ -o Fano Fano.cpp    (или g++ -o Fano Fano.cpp)
// Запуск:      ./Fano [путь_к_файлу_с_текстом]

#include <cmath>
#include <cstdio>
#include <cstring>

#define MAX_SYM 512     // максимум различных символов в алфавите
#define MAX_LEN 64      // максимум длины кодового слова
#define W_SYM 8         // ширина колонки "Символ" в таблице п.2
#define W_PROB 20       // ширина колонки "Вероятность символа"
#define W_CODE 24       // ширина колонки "Кодовое слово"
#define W_LEN 20        // ширина колонки "Длина кодового слова"
#define W_KRAFT 28      // ширина колонки "Неравенство Крафта" в таблице п.3
#define W_ENT 26        // ширина колонки "Энтропия исходного текста"
#define W_LCP 30        // ширина колонки "Средняя длина кодового слова"
#define W_RED 24        // ширина колонки "Избыточность кода Фано"

// Один символ алфавита: кодовая точка UTF-8, его байты и частота появления n_i.
struct Sym {
    int code;   // кодовая точка символа (Unicode), для различения символов
    char ch[4]; // байты символа в UTF-8, для печати в таблице
    int count;  // n_i — сколько раз символ встретился в тексте
};

Sym alpha[MAX_SYM];              // алфавит: различные символы и их частоты n_i
int n_alpha = 0;                 // n — размер алфавита (различных символов)
int total = 0;                   // N — общее количество прочитанных символов
double P[MAX_SYM + 1];           // P — вероятности по убыванию, индексы 1..n
int C[MAX_SYM + 1][MAX_LEN + 1]; // C — разряды кодовых слов, индексы 1..n, 1..Length
int Length[MAX_SYM + 1];         // Length — длины кодовых слов, индексы 1..n

// Читает из файла f следующий символ кириллицы (2 байта UTF-8: 0xD0 или 0xD1).
// cp — кодовая точка символа, ch — его байты в UTF-8.
// Возвращает 1 при успехе и 0, если символ прочитать не удалось (конец файла).
int read_utf8(FILE *f, int *cp, char *ch) {
    int c0;
    while ((c0 = fgetc(f)) != EOF) {
        unsigned char b0 = (unsigned char)c0;
        if (b0 == 0xD0 || b0 == 0xD1) {
            int c1 = fgetc(f);
            if (c1 == EOF)
                return 0;
            unsigned char b1 = (unsigned char)c1;
            ch[0] = (char)b0;
            ch[1] = (char)b1;
            ch[2] = '\0';
            *cp = ((int)(b0 & 0x1F) << 6) | (b1 & 0x3F);
            return 1;
        }
    }
    return 0;
}

// Печатает строку s и дополняет её пробелами до ширины wide символов UTF-8
// ( setw посчитал бы байты, а русская буква занимает 2 байта, поэтому
//   символы считаем вручную по началу каждой кодовой последовательности).
void printCell(const char *s, int wide) {
    int len = 0;
    printf("%s", s);
    for (const unsigned char *p = (const unsigned char *)s; *p; p++) {
        if ((*p & 0xC0) != 0x80)
            len++; // считаем начало каждого символа, а не байты
    }
    for (int i = len; i < wide; i++)
        printf(" ");
}

// Функция Med(L,R) псевдокода пособия: находит медиану массива P — индекс
// m (L <= m < R), для которого величина |sum(i=L..m) p_i - sum(i=m+1..R) p_i|
// минимальна (пособие: "Функция Med находит медиану массива P").
// Индекс m = R не рассматривается: правая часть была бы пустой, а при
// положительных вероятностях такая разбивка не бывает минимумом разности.
int Med(int L, int R) {
    int m = L;              // найденная медиана — возвращаемый индекс
    double best = -1.0;     // лучшая (пока минимальная) разность сумм
    int i, j;
    for (i = L; i < R; i++) { // перебор точки разреза: первая часть L..i
        double SL = 0.0;      // сумма вероятностей первой части
        double SR = 0.0;      // сумма вероятностей второй части
        for (j = L; j <= i; j++)
            SL = SL + P[j];
        for (j = i + 1; j <= R; j++)
            SR = SR + P[j];
        double diff = fabs(SL - SR);
        if (best < 0.0 || diff < best) {
            best = diff;
            m = i;
        }
    }
    return m;
}

// Медиана из алгоритма А2 построения почти оптимального дерева поиска
// (пособие, п. 14.3): сумма весов wes рабочей части делится пополам —
// выбирается индекс m, у которого сумма элементов L..m-1 меньше wes/2,
// а сумма L..m не меньше wes/2 (вершина-медиана Vk).
int MedA2(int L, int R) {
    double wes = 0.0;   // wes — сумма весов (вероятностей) рабочей части
    double summa = 0.0; // summa — накопленная сумма перед текущим элементом
    int m = R - 1;      // m — выбранная медиана (значение по умолчанию)
    int i;
    for (i = L; i <= R; i++) // DO (i=L, L+1, ..., R) wes = wes + V[i].w
        wes = wes + P[i];
    for (i = L; i <= R - 1; i++) { // DO (i=L, L+1, ..., R-1)
        if (summa < wes / 2.0 && summa + P[i] >= wes / 2.0) {
            m = i; // нашли вершину-медиану Vk — выход из цикла
            break;
        }
        summa = summa + P[i];
    }
    return m; // защита: без выхода m = R-1, иначе рекурсия Fano не закончится
}

// Алгоритм Фано (псевдокод пособия): строит кодовые слова для отрезка [L..R]
// массива P. k — длина уже построенной части элементарных кодов;
// med — указатель на функцию вычисления медианы: Med — код Фано заданий 2–3,
// MedA2 — вариант кода Фано с медианой алгоритма А2 (задание 4).
void Fano(int L, int R, int k, int (*med)(int, int)) {
    if (L < R) {
        k = k + 1;   // удлиняем элементарные коды на один разряд
        int m = med(L, R); // m := Med(L,R) — точка разбиения отрезка
        int i;
        for (i = L; i <= R; i++) { // DO (i=L, ..., R)
            if (i <= m) { // буквам первой части приписывается 0
                C[i][k] = 0;
                Length[i] = Length[i] + 1;
            } else { // буквам второй части приписывается 1
                C[i][k] = 1;
                Length[i] = Length[i] + 1;
            }
        }
        Fano(L, m, k, med);     // рекурсия по левой части
        Fano(m + 1, R, k, med); // рекурсия по правой части
    }
}

// Собирает кодовое слово символа i из разрядов C[i][1..Length[i]] в строку buf.
void makeCode(int i, char *buf) {
    int j;
    for (j = 1; j <= Length[i]; j++)
        buf[j - 1] = C[i][j] ? '1' : '0';
    buf[Length[i]] = '\0';
}

// Обнуляет массивы разрядов C и длин Length перед построением нового
// варианта кода Фано (нужно для задания 4, где код строится заново).
void clearCodes(void) {
    int i, j;
    for (i = 0; i <= MAX_SYM; i++) {
        Length[i] = 0;
        for (j = 0; j <= MAX_LEN; j++)
            C[i][j] = 0;
    }
}

// Выводит таблицу п.2: Символ | Вероятность символа |
// Кодовое слово | Длина кодового слова.
void printTableCode(const char *title) {
    char prob[32];        // строковое представление вероятности P_i
    char code[MAX_LEN + 2]; // строковое представление кодового слова
    int i;
    printf("\n%s\n", title);
    printCell("Символ", W_SYM);
    printCell("Вероятность символа", W_PROB);
    printCell("Кодовое слово", W_CODE);
    printCell("Длина кодового слова", W_LEN);
    printf("\n");
    for (i = 1; i <= n_alpha; i++) {
        snprintf(prob, sizeof(prob), "%.6g", P[i]);
        makeCode(i, code);
        printCell(alpha[i - 1].ch, W_SYM);
        printCell(prob, W_PROB);
        printCell(code, W_CODE);
        printf("%d\n", Length[i]);
    }
}

// Выводит таблицу п.3: Неравенство Крафта | Энтропия исходного текста |
// Средняя длина кодового слова | Избыточность кода Фано.
void printTableStats(const char *title) {
    char cellKraft[64]; // строковое представление неравенства Крафта
    char cellH[32];     // строковое представление энтропии H
    char cellL[32];     // строковое представления средней длины Lcp
    char cellR[32];     // строковое представление избыточности r
    double kraft = 0.0; // sum(2^-Length[i]) — левая часть неравенства Крафта
    double H = 0.0;     // H — энтропия исходного текста
    double Lcp = 0.0;   // Lcp — средняя длина кодового слова
    double r;           // r = Lcp - H — избыточность кода Фано
    int i;
    for (i = 1; i <= n_alpha; i++) {
        kraft = kraft + pow(2.0, -Length[i]);
        H = H - P[i] * log2(P[i]);
        Lcp = Lcp + P[i] * Length[i];
    }
    r = Lcp - H;
    snprintf(cellKraft, sizeof(cellKraft), "%.6f <= 1 (%s)", kraft,
             (kraft <= 1.0 + 1e-9) ? "выполняется" : "НЕ выполняется");
    snprintf(cellH, sizeof(cellH), "%.6f", H);
    snprintf(cellL, sizeof(cellL), "%.6f", Lcp);
    snprintf(cellR, sizeof(cellR), "%.6f", r);
    printf("\n%s\n", title);
    printCell("Неравенство Крафта", W_KRAFT);
    printCell("Энтропия исходного текста", W_ENT);
    printCell("Средняя длина кодового слова", W_LCP);
    printCell("Избыточность кода Фано", W_RED);
    printf("\n");
    printCell(cellKraft, W_KRAFT);
    printCell(cellH, W_ENT);
    printCell(cellL, W_LCP);
    printCell(cellR, W_RED);
    printf("\n");
}

int main(int argc, char **argv) {
    // Имя файла с произведением: аргумент командной строки или файл
    // по умолчанию (~11 КБ, не меньше 10 КБ по условию задания).
    const char *path = (argc > 1) ? argv[1] : "proizvedenie_11kb.txt";
    FILE *f = fopen(path, "rb");
    if (!f) {
        printf("Ошибка открытия файла: %s\n", path);
        return 1;
    }

    int cp;   // кодовая точка очередного символа
    char ch[4]; // байты очередного символа в UTF-8
    int i, j;

    // Подсчёт частот: для каждого символа увеличиваем n_i, новый символ
    // добавляем в алфавит (линейный поиск по уже известным символам).
    while (read_utf8(f, &cp, ch)) {
        total++; // N — общее число символов в файле
        int idx = -1;
        for (i = 0; i < n_alpha; i++) {
            if (alpha[i].code == cp) {
                idx = i;
                break;
            }
        }
        if (idx != -1) {
            alpha[idx].count++; // символ уже встречался — увеличиваем n_i
        } else if (n_alpha < MAX_SYM) {
            alpha[n_alpha].code = cp;
            strcpy(alpha[n_alpha].ch, ch);
            alpha[n_alpha].count = 1; // первый раз встретился — n_i = 1
            n_alpha++;
        }
    }
    fclose(f);

    if (n_alpha == 0) {
        printf("В файле %s нет символов кириллицы\n", path);
        return 1;
    }

    int n = n_alpha; // n — размер алфавита

    // Вычисление вероятности: P_i = n_i / N, индексы 1..n.
    for (i = 0; i < n; i++)
        P[i + 1] = (double)alpha[i].count / total;

    // Сортировка вероятностей по убыванию (пузырьком) — Фано требует
    // упорядоченный по убыванию массив P; символы едут вместе с P.
    for (i = 1; i <= n - 1; i++) {
        for (j = 1; j <= n - i; j++) {
            if (P[j] < P[j + 1]) {
                double tp = P[j];
                P[j] = P[j + 1];
                P[j + 1] = tp;
                Sym tsym = alpha[j - 1];
                alpha[j - 1] = alpha[j];
                alpha[j] = tsym;
            }
        }
    }

    printf("Файл: %s\n", path);
    printf("Всего символов N = %d, различных букв: %d\n", total, n);

    // Задание 2: строим код Фано по псевдокоду пособия (медиана — функция Med)
    // и выводим кодовую таблицу.
    clearCodes();
    Fano(1, n, 0, Med);
    printTableCode("Задание 2. Кодовая таблица кода Фано");

    // Задание 3: для построенного кода проверяем неравенство Крафта,
    // считаем энтропию, среднюю длину кодового слова и избыточность.
    printTableStats("Задание 3. Оценка кода Фано");

    // Задание 4: строим код Фано заново, но медиану вычисляем функцией
    // из алгоритма А2, и выводим таблицы п.2 и п.3 для этого варианта.
    clearCodes();
    Fano(1, n, 0, MedA2);
    printTableCode("Задание 4. Таблица п.2 для кода Фано с медианой алгоритма А2");
    printTableStats("Задание 4. Таблица п.3 для кода Фано с медианой алгоритма А2");

    return 0;
}
